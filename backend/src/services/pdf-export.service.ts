import PDFDocument from 'pdfkit';
import { Response } from 'express';

export class PdfExportService {
  static generateReportPdf(res: Response, reportData: {
    title: string;
    referenceId: string;
    generatedAt: Date;
    generatedBy: string;
    dateRange: string;
    intersectionName?: string;
    headers: string[];
    rows: string[][];
    summary: Record<string, any>;
  }) {
    const doc = new PDFDocument({ margin: 40, size: 'A4' });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="Report_${reportData.referenceId}.pdf"`);

    doc.pipe(res);

    // Header / Branding
    doc
      .fontSize(16)
      .fillColor('#0f172a')
      .text('WACHEMO UNIVERSITY', { align: 'center', bold: true } as any)
      .fontSize(12)
      .fillColor('#334155')
      .text('College of Engineering and Technology — Department of Software Engineering', { align: 'center' })
      .text('SEng4162: Real Time and Embedded Systems — Traffic Light Automation', { align: 'center' })
      .moveDown(0.8);

    doc
      .strokeColor('#cbd5e1')
      .lineWidth(1)
      .moveTo(40, doc.y)
      .lineTo(555, doc.y)
      .stroke()
      .moveDown(0.8);

    // Report Title & Metadata
    doc
      .fontSize(14)
      .fillColor('#1e293b')
      .text(reportData.title, { bold: true } as any)
      .moveDown(0.4);

    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(`Reference ID: ${reportData.referenceId}    |    Generated: ${reportData.generatedAt.toLocaleString()}`)
      .text(`Generated By: ${reportData.generatedBy}    |    Date Scope: ${reportData.dateRange}`)
      .text(`Intersection: ${reportData.intersectionName || 'All Authorized Intersections'}`)
      .moveDown(0.8);

    // Summary Box
    doc
      .rect(40, doc.y, 515, 36)
      .fillAndStroke('#f8fafc', '#e2e8f0');

    const summaryY = doc.y - 30;
    doc
      .fontSize(9)
      .fillColor('#1e293b');

    const summaryText = Object.entries(reportData.summary)
      .map(([k, v]) => `${k}: ${v}`)
      .join('    |    ');

    doc.text(summaryText, 50, summaryY + 8);
    doc.moveDown(1.5);

    // Data Table
    const startX = 40;
    let currentY = doc.y + 10;
    const colWidth = Math.floor(515 / reportData.headers.length);

    // Table Header
    doc
      .rect(startX, currentY, 515, 20)
      .fill('#0f172a');

    doc.fillColor('#ffffff').fontSize(8);
    reportData.headers.forEach((header, i) => {
      doc.text(header, startX + i * colWidth + 4, currentY + 6, {
        width: colWidth - 8,
        align: 'left',
      });
    });

    currentY += 20;

    // Table Rows
    doc.fillColor('#1e293b').fontSize(8);
    reportData.rows.forEach((row, rowIndex) => {
      // New page check
      if (currentY > 750) {
        doc.addPage();
        currentY = 40;
      }

      if (rowIndex % 2 === 1) {
        doc.rect(startX, currentY, 515, 18).fill('#f1f5f9');
      }

      doc.fillColor('#1e293b');
      row.forEach((cell, i) => {
        doc.text(String(cell || '-'), startX + i * colWidth + 4, currentY + 5, {
          width: colWidth - 8,
          align: 'left',
        });
      });

      currentY += 18;
    });

    // Footer with Page Numbers
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc
        .fontSize(8)
        .fillColor('#94a3b8')
        .text(
          `Page ${i + 1} of ${range.count}  •  Official Traffic Management System Audit Record`,
          40,
          780,
          { align: 'center', width: 515 }
        );
    }

    doc.end();
  }
}
